/*
  A API fornece os títulos das histórias, mas nem sempre fornece
  o texto completo de cada história.

  Esta função procura primeiro um resumo específico.
  Se ainda não existir, cria uma mensagem segura usando o
  próprio título da história, sem inventar acontecimentos.
*/

export function getStorySummary(characterName, storyTitle) {
  const characterStories = storySummaries[characterName]

  if (characterStories && characterStories[storyTitle]) {
    return characterStories[storyTitle]
  }

  return `“${storyTitle}” é uma história relacionada a ${characterName}. A API disponibiliza esse título como um dos acontecimentos associados ao personagem, mas não fornece o texto completo dessa história.`
}

export default storySummaries